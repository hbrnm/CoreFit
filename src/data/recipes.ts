import { FOODS } from './foods';
import type { RecipeIngredient } from '../lib/db';

export type RecipeCuisine = 'mediterranean' | 'world' | 'tastemotions';

export interface CatalogRecipe {
  id: string;
  name: string;
  cuisine: RecipeCuisine;
  /** de ce ține de foame, fără promisiuni medicale */
  summary: string;
  servings: number;
  minutes: number;
  steps: string[];
  ingredients: RecipeIngredient[];
}

const BY_ID = new Map(FOODS.map((food) => [food.id, food]));

function ing(foodId: string, grams: number): RecipeIngredient {
  const food = BY_ID.get(foodId);
  if (!food) throw new Error(`Aliment lipsă din catalog: ${foodId}`);
  return {
    name: food.name,
    grams,
    kcal100: food.kcal100,
    protein100: food.protein100,
    carbs100: food.carbs100,
    fat100: food.fat100,
    fiber100: food.fiber100,
    sugar100: food.sugar100,
    sodium100: food.sodium100,
  };
}

